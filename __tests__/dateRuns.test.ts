import {
  bestRuns,
  dayRuns,
  rangeLabels,
  runLabel,
} from '@/lib/bucket/dateVotes';

const t = (day: string, users: string[]) => ({ day, users });

describe('되는 날을 기간으로 묶기', () => {
  it('연속되고 되는 사람이 같으면 한 기간으로 묶는다', () => {
    const runs = dayRuns([
      t('2026-11-20', ['a', 'b']),
      t('2026-11-21', ['b', 'a']),
      t('2026-11-22', ['a', 'b']),
      t('2026-11-23', ['a']),
      t('2026-11-25', ['a']),
    ]);
    expect(runs.map((r) => [r.from, r.to, r.length])).toEqual([
      ['2026-11-20', '2026-11-22', 3],
      ['2026-11-23', '2026-11-23', 1],
      ['2026-11-25', '2026-11-25', 1],
    ]);
  });

  it('많이 되는 기간이 먼저, 같으면 긴 기간이 먼저', () => {
    const best = bestRuns([
      t('2026-11-20', ['a']),
      t('2026-11-27', ['a', 'b']),
      t('2026-11-28', ['a', 'b']),
      t('2026-11-30', ['a', 'b']),
    ]);
    expect(best.map((r) => r.from)).toEqual([
      '2026-11-27',
      '2026-11-30',
      '2026-11-20',
    ]);
  });

  it('기간 이름: 같은 달은 끝에 달을 빼고, 달이 다르면 붙인다', () => {
    expect(runLabel('2026-11-20', '2026-11-23')).toBe(
      '11월 20일 (금) ~ 23일 (월)'
    );
    expect(runLabel('2026-11-30', '2026-12-01')).toBe(
      '11월 30일 (월) ~ 12월 1일 (화)'
    );
    expect(runLabel('2026-11-27', '2026-11-27')).toBe('11월 27일 (금)');
  });

  it('내가 고른 날을 순서 없이 줘도 기간으로 묶는다', () => {
    expect(rangeLabels(['2026-11-27', '2026-11-21', '2026-11-20'])).toEqual([
      '11월 20일 (금) ~ 21일 (토)',
      '11월 27일 (금)',
    ]);
  });
});
